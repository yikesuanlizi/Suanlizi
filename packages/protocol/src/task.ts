/**
 * TaskStep 六态集合。HarnessPlanNode 保持既有四态，不扩成六态；
 * 六态只存在于展示层与验收层，由 planProjection 派生。
 *
 * 计划 §14.2 映射表 / mapping from HarnessPlanNode.status:
 *
 * | HarnessPlanNode.status | Evidence 结果                              | TaskStep.status |
 * |------------------------|--------------------------------------------|-----------------|
 * | pending                | -                                          | pending         |
 * | in_progress            | -                                          | in_progress     |
 * | completed              | evidenceIds 非空且 Evidence 有效           | verified        |
 * | completed              | 无证据或 Evidence 无效                     | claimed         |
 * | failed                 | -                                          | failed          |
 * | -                      | 用户或系统显式跳过                          | skipped         |
 *
 * 规则：模型声明 completed 时投影层不得直接写 verified；claimed 可显示但不可验收；
 * skipped 不得由模型用来绕过验收，必须由用户 redirect 或明确策略触发。
 */
export const TASK_STEP_STATUSES = [
  'pending',
  'in_progress',
  'claimed',
  'verified',
  'failed',
  'skipped',
] as const;

export type TaskStepStatus = (typeof TASK_STEP_STATUSES)[number];

/** 可显示但不可验收的状态集合（模型自述完成、缺有效证据）。 */
/** Statuses that may be displayed but never satisfy acceptance criteria. */
export const TASK_STEP_NON_ACCEPTABLE_STATUSES: readonly TaskStepStatus[] = ['claimed'];

export function isTaskStepStatus(value: string): value is TaskStepStatus {
  return (TASK_STEP_STATUSES as readonly string[]).includes(value);
}

/** 计划中的单个步骤投影。/ One projected plan step. */
export interface TaskStep {
  /**
   * 系统分配的稳定 id；模型不能生成或修改。模型输出新计划时，已有步骤只能通过 id 引用，
   * 新步骤不携带 id，由投影层补发。
   * System-assigned stable id; the model may neither generate nor modify it. New steps come without
   * an id and are assigned by planProjection.
   */
  id: string;
  description: string;
  status: TaskStepStatus;
  /** 支撑该步骤的证据 id 集合；verified 要求其中至少存在一条有效 Evidence。 */
  evidenceIds: string[];
  dependsOn?: string[];
  failureReason?: string;
  startedAt?: string;
  completedAt?: string;
}

