// ─── Task 状态（目标层） ─────────────────────────────────────────────────────
// Task status (goal layer).

/** Task 的目标层完整状态集合。/ Full goal-layer status set of a Task. */
export const TASK_STATUSES = [
  'pending',
  'running',
  'blocked',
  'completed',
  'failed',
  'cancelled',
] as const;

export type TaskStatus = (typeof TASK_STATUSES)[number];

/**
 * Task 状态机的唯一允许迁移表。终态（completed / cancelled / failed）故意没有任何出口。
 * The single allowed transition table for Task status. Terminal states intentionally have no exits.
 */
export const TASK_STATUS_TRANSITIONS: Readonly<Record<TaskStatus, readonly TaskStatus[]>> = {
  pending: ['running', 'blocked', 'cancelled', 'failed'],
  running: ['blocked', 'completed', 'failed', 'cancelled'],
  blocked: ['running', 'cancelled', 'failed'],
  completed: [],
  cancelled: [],
  failed: [],
};

export const TASK_STATUS_TERMINAL_STATES: ReadonlySet<TaskStatus> = new Set([
  'completed',
  'cancelled',
  'failed',
]);

export function isTaskStatus(value: string): value is TaskStatus {
  return (TASK_STATUSES as readonly string[]).includes(value);
}

/** 判断 Task 是否处于终态（不可再迁移，只能通过新 Run/新 Task 继续）。 */
/** Whether a Task status is terminal (only a new Run or new Task may continue). */
export function isTaskTerminalState(status: TaskStatus): boolean {
  return TASK_STATUS_TERMINAL_STATES.has(status);
}

export function canTransitionTaskStatus(from: TaskStatus, to: TaskStatus): boolean {
  return TASK_STATUS_TRANSITIONS[from].includes(to);
}

export const TASK_STATUS_TRANSITION_MAP = TASK_STATUS_TRANSITIONS;
export const TASK_STATUS_TERMINAL_STATE_SET = TASK_STATUS_TERMINAL_STATES;

