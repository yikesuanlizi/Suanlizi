/** TaskRun 的过程态集合。/ Full process-state set of a TaskRun. */
export const TASK_RUN_STATES = [
  'queued',
  'running',
  'paused',
  'blocked',
  'completed',
  'failed',
  'cancelled',
  'interrupted',
] as const;

export type TaskRunState = (typeof TASK_RUN_STATES)[number];

/**
 * TaskRun 状态机的唯一迁移表（计划 §11.4）。禁止在实现层用散落 if/else 另起一套迁移规则。
 * The single TaskRun transition table; implementations must not rely on scattered if/else rules.
 *
 * 补充语义：
 * - `blocked -> queued` 表示等待用户输入后重新排队。
 * - `interrupted` 恢复前必须核对 Agent Checkpoint。
 * - 终态无出口；`retry` 只创建新 Run，不修改旧 Run 终态。
 *
 * 对 §11.4 原表的必要补边（计划表只列了出口，未给 completed / interrupted 任何入口，
 * 会使 GoalRun 成功落终态与 §11.2 恢复扫描标记 interrupted 两条合法路径无法表达）：
 * - `running -> completed`：执行成功且验收通过后由上层（P3 GoalEvaluator gate）落入。
 * - `queued|running|paused|blocked -> interrupted`：崩溃/重启恢复扫描的 system-only 迁移，
 *   调用方必须先核对 Agent Checkpoint 才能写入（§11.2）。
 */
export const TASK_RUN_TRANSITIONS: Readonly<Record<TaskRunState, readonly TaskRunState[]>> = {
  queued: ['running', 'blocked', 'cancelled', 'failed', 'interrupted'],
  running: ['paused', 'blocked', 'cancelled', 'failed', 'completed', 'interrupted'],
  paused: ['running', 'cancelled', 'failed', 'interrupted'],
  blocked: ['queued', 'cancelled', 'failed', 'interrupted'],
  interrupted: ['running', 'queued', 'cancelled', 'failed'],
  completed: [],
  cancelled: [],
  failed: [],
};

export const TASK_RUN_TERMINAL_STATES: ReadonlySet<TaskRunState> = new Set([
  'completed',
  'cancelled',
  'failed',
]);

// 与 OpsTask 资产保持同构的别名集合，便于通用状态机模块后续接管。
// Aliases mirroring the OpsTask asset names so the shared state-machine module can take over later.
export const TASK_RUN_TRANSITION_MAP = TASK_RUN_TRANSITIONS;
export const TASK_RUN_TERMINAL_STATE_SET = TASK_RUN_TERMINAL_STATES;

export function isTaskRunState(value: string): value is TaskRunState {
  return (TASK_RUN_STATES as readonly string[]).includes(value);
}

export function isTaskRunTerminalState(state: TaskRunState): boolean {
  return TASK_RUN_TERMINAL_STATES.has(state);
}

export function canTransitionTaskRun(from: TaskRunState, to: TaskRunState): boolean {
  return TASK_RUN_TRANSITIONS[from].includes(to);
}

export const isValidTaskRunTransition = canTransitionTaskRun;

/** TaskRun 的过程态承载实体。/ A single execution attempt of a Task. */
export interface TaskRun {
  id: string;
  taskId: string;
  threadId: string;
  kind: TaskRunKind;
  status: TaskRunState;
  /** kind='goal' 时关联既有 Harness run id。 */
  harnessRunId?: string;
  /** kind='workflow' 时关联 WorkflowRunRecord id。 */
  workflowRunId?: string;
  /** kind='workflow' 时的子类型；kind='goal' 时必须缺省。 */
  /** Workflow subtype; only meaningful when kind === 'workflow'. */
  workflowKind?: WorkflowKind;
  startedAt?: string;
  updatedAt: string;
  completedAt?: string;
  error?: string;
  /**
   * 指向现有 Agent Checkpoint（packages/protocol/src/types.ts 的 `Checkpoint`）的标识。
   * 恢复真相只存在于 Agent Checkpoint，禁止在 Task 表与 Checkpoint 之间各写一份恢复机制。
   * 恢复顺序：读 task_runs.checkpointId → 读 Agent Checkpoint → 按 executionStatus/decisionRequest
   * 决定 resume / 继续停止 / 还原 pending decision / 落终态 / 标记 interrupted → 回写 task_runs。
   *
   * References the existing Agent `Checkpoint` in ./types.js. It is NOT a new recovery mechanism:
   * the Agent Checkpoint stays the single source of resume truth, and task_runs only mirrors it.
   */
  checkpointId?: string;
  /** 乐观锁版本；每次成功迁移递增。/ Optimistic-lock version, incremented per transition. */
  version: number;
}

