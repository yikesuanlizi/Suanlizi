/** 迁移表与 Task 状态共用 `from`/`to` 描述，允许两类状态字符串。 */
type TaskRunStatusLike = TaskStatus | TaskRunState | WorkflowRunStatus | string;

/** 带稳定机器可读错误码的任务协议错误。 / Protocol error carrying a stable machine-readable code. */
export class TaskError extends Error {
  readonly code: TaskErrorCode;
  readonly details?: Readonly<TaskErrorDetails>;

  constructor(code: TaskErrorCode, message: string, details?: TaskErrorDetails) {
    super(message);
    this.name = 'TaskError';
    this.code = code;
    this.details = details;
  }
}

/**
 * 断言 TaskRun 迁移合法（计划 §11.4）。终态优先抛 TASK_TERMINAL_STATE，
 * 其余非法迁移抛 TASK_INVALID_TRANSITION。
 * Asserts a TaskRun transition; terminal sources report TASK_TERMINAL_STATE first.
 */
export function assertTaskRunTransition(from: TaskRunState, to: TaskRunState): void {
  if (isTaskRunTerminalState(from)) {
    throw new TaskError(
      'TASK_TERMINAL_STATE',
      `Task run in terminal state ${from} cannot transition to ${to}`,
      { from, to },
    );
  }
  if (!canTransitionTaskRun(from, to)) {
    throw new TaskError(
      'TASK_INVALID_TRANSITION',
      `Task run cannot transition from ${from} to ${to}`,
      { from, to },
    );
  }
}

/** 断言 Task 目标层迁移合法；终态优先抛 TASK_TERMINAL_STATE。 */
/** Asserts a Task status transition; terminal sources report TASK_TERMINAL_STATE first. */
export function assertTaskStatusTransition(from: TaskStatus, to: TaskStatus): void {
  if (isTaskTerminalState(from)) {
    throw new TaskError(
      'TASK_TERMINAL_STATE',
      `Task in terminal status ${from} cannot transition to ${to}`,
      { from, to },
    );
  }
  if (!canTransitionTaskStatus(from, to)) {
    throw new TaskError(
      'TASK_INVALID_TRANSITION',
      `Task cannot transition from ${from} to ${to}`,
      { from, to },
    );
  }
}

/**
 * API 层乐观锁版本校验。成功返回 true，冲突时抛 TASK_VERSION_CONFLICT。
 * Optimistic-lock check used by the API layer; throws TASK_VERSION_CONFLICT on mismatch.
 */
export function validateTaskVersion(actualVersion: number, expectedVersion: number): true {
  if (
    !Number.isSafeInteger(actualVersion) ||
    !Number.isSafeInteger(expectedVersion) ||
    actualVersion !== expectedVersion
  ) {
    throw new TaskError(
      'TASK_VERSION_CONFLICT',
      `Task version conflict: expected ${expectedVersion}, got ${actualVersion}`,
      { actualVersion, expectedVersion },
    );
  }
  return true;
}

export const assertTaskVersion = validateTaskVersion;

export function isTaskVersionMatch(actualVersion: number, expectedVersion: number): boolean {
  return (
    Number.isSafeInteger(actualVersion) &&
    Number.isSafeInteger(expectedVersion) &&
    actualVersion === expectedVersion
  );
}

